  /// 传入公历y年获得该年第n个节气的公历日期
  /// [y] 公历年(1900-2100)
  /// [n] 二十四节气中的第几个节气(1~24)；从n=1(小寒)算起
  /// 返回日期的日（1-31）
  static int getTerm(int y, int n) {
    if (y < 1900 || y > 2100) {
      return -1;
    }
    if (n < 1 || n > 24) {
      return -1;
    }
    String table = S_TERM_INFO[y - 1900];
    List<int> info = [];
    for (int i = 0; i < 6; i++) {
      info.add(int.parse(table.substring(i * 5, 5 * (i + 1)), radix: 16));
    }
    List<String> calday = [];
    for (int i = 0; i < 6; i++) {
      String infoStr = info[i].toString();
      calday.add(infoStr.substring(0, 1));
      calday.add(infoStr.substring(1, 3));
      calday.add(infoStr.substring(3, 4));
      calday.add(infoStr.substring(4, 6));
    }

    return int.parse(calday[n - 1]);
  }

  /// 根据日期获取节气
  /// [year] 公历年
  /// [month] 公历月，从1开始
  /// [day] 公历日，从1开始
  /// 返回节气名称，若不是节气则返回空字符串
  static String getTermFromDate(int year, int month, int day) {
    if (year < 1900 || year > 2100) {
      return '';
    }
    String termTable = S_TERM_INFO[year - 1900];

    // 节气速查表中每5个字符含有4个节气，通过月份直接计算偏移
    int segment = (month + 1) ~/ 2 - 1;
    int termInfo = int.parse(termTable.substring(segment * 5, (segment + 1) * 5), radix: 16);
    String termInfoStr = termInfo.toString();
    List<String> segmentTable = [
      termInfoStr.substring(0, 1),
      termInfoStr.substring(1, 3),
      termInfoStr.substring(3, 4),
      termInfoStr.substring(4, 6),
    ];

    // 奇数月份的节气在前2个，偶数月份的节气在后两个
    int segmentOffset = (month & 1) == 1 ? 0 : 2;
    if (day == int.parse(segmentTable[segmentOffset])) {
      return TERMS[segment * 4 + segmentOffset];
    }
    if (day == int.parse(segmentTable[segmentOffset + 1])) {
      return TERMS[segment * 4 + segmentOffset + 1];
    }
    return '';
  }
